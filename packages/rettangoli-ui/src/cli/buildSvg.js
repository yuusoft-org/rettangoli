import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, basename } from 'node:path';

function getAllSvgFiles(dir) {
  const svgFiles = [];
  
  function traverse(currentDir) {
    const files = readdirSync(currentDir);
    
    for (const file of files) {
      const fullPath = join(currentDir, file);
      const stats = statSync(fullPath);
      
      if (stats.isDirectory()) {
        traverse(fullPath);
      } else if (file.endsWith('.svg')) {
        svgFiles.push(fullPath);
      }
    }
  }
  
  traverse(dir);
  return svgFiles;
}

// Strips the metadata in front of the SVG markup. A file whose first non-blank
// line is '---' has a frontmatter block that ends at the next '---' line.
// Otherwise everything up to the first '---' line is metadata (the legacy
// `name: x\n---\n<svg>` format), and a file with no '---' line is kept as is.
function removeFrontmatter(content) {
  const lines = content.split('\n');
  const isSeparator = (line) => line.trim() === '---';
  let separator = lines.findIndex(isSeparator);

  if (separator === -1) {
    return content;
  }

  const firstContentLine = lines.findIndex((line) => line.trim() !== '');
  if (separator === firstContentLine) {
    const closing = lines.findIndex((line, i) => i > separator && isSeparator(line));
    if (closing !== -1) {
      separator = closing;
    }
  }

  return lines.slice(separator + 1).join('\n').trim();
}

// A script that registers `icons` with rtgl.setIcons when it runs after the
// Rettangoli UI script. Run before it, or with a version older than 1.29, it
// falls back to the deprecated window.rtglIcons, which Rettangoli UI still
// reads, so the file works in either load order.
export const createIconsScript = (icons) => {
  const entries = Object.entries(icons).map(
    ([name, svg]) => `    ${JSON.stringify(name)}: ${JSON.stringify(svg)}`,
  );
  return [
    "// Generated by `rtgl ui build-svg`.",
    "(() => {",
    "  const icons = {",
    entries.join(",\n"),
    "  };",
    "  if (window.rtgl && window.rtgl.setIcons) {",
    "    window.rtgl.setIcons(icons);",
    "  } else {",
    "    window.rtglIcons = Object.assign(window.rtglIcons || {}, icons);",
    "  }",
    "})();",
    "",
  ].join("\n");
};

const buildSvgIcons = (options) => {
  const { dir, outfile } = options;
  
  if (!dir || !outfile) {
    console.error('Error: Both dir and outfile options are required');
    return;
  }
  
  console.log(`Scanning for SVG files in: ${dir}`);
  
  const svgFiles = getAllSvgFiles(dir);
  
  if (svgFiles.length === 0) {
    console.log('No SVG files found');
    return;
  }
  
  console.log(`Found ${svgFiles.length} SVG files`);
  
  const icons = {};
  const iconPaths = new Map();
  
  for (const filePath of svgFiles) {
    const fileName = basename(filePath, '.svg');
    if (iconPaths.has(fileName)) {
      console.warn(
        `Duplicate icon name "${fileName}": ${filePath} replaces ${iconPaths.get(fileName)}`,
      );
    }
    iconPaths.set(fileName, filePath);
    let content = readFileSync(filePath, 'utf8');
    
    content = removeFrontmatter(content);
    
    content = content.replace(/\n/g, ' ').replace(/\s+/g, ' ').trim();
    
    icons[fileName] = content;
  }
  
  writeFileSync(outfile, createIconsScript(icons));
  
  console.log(`SVG icons written to: ${outfile}`);
  console.log(`Total icons: ${Object.keys(icons).length}`);
};

export default buildSvgIcons;